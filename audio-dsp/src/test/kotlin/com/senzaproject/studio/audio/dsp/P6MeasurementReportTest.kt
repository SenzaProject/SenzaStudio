package com.senzaproject.studio.audio.dsp

import com.senzaproject.studio.audio.engine.BassParameters
import com.senzaproject.studio.audio.engine.CompressorParameters
import com.senzaproject.studio.audio.engine.DynamicsParameters
import com.senzaproject.studio.audio.engine.EngineParameters
import com.senzaproject.studio.audio.engine.EqBand
import com.senzaproject.studio.audio.engine.EqParameters
import com.senzaproject.studio.audio.engine.ImagingParameters
import com.senzaproject.studio.audio.engine.LoudnessParameters
import com.senzaproject.studio.audio.engine.SpatialMode
import com.senzaproject.studio.audio.engine.SpatialParameters
import java.io.File
import java.util.Locale
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Callback profiling for P6: how much of real time each module (and the whole chain) needs, and the
 * before/after cost of the optimised loops. Writes build/reports/p6-measurements.md (uploaded by CI).
 * The numbers describe the machine that ran the test (a CI VM or a laptop), NOT a phone; they are
 * for comparing modules and revisions with each other. Only one catastrophic-regression bound is
 * asserted (full chain at least 5x real time) so the build is not flaky on busy runners.
 */
class P6MeasurementReportTest {
    private fun f(v: Double, digits: Int = 2) = String.format(Locale.US, "%.${digits}f", v)

    private class Row(val name: String, val realtimeFactor: Double, val loadPercent: Double, val microsPerBlock: Double, val worstBlockMicros: Double)

    private val block = 1024

    private fun scenario(name: String, p: EngineParameters, seconds: Int = 20): Row {
        val chain = DspChain(FS).also { it.configure(p) }
        val src = stereoNoise(0.4f, block * 64, 7, 8)
        val buf = FloatArray(block * 2)
        val blocks = FS * seconds / block
        // Warm-up (JIT) is not measured.
        for (b in 0 until FS * 4 / block) {
            System.arraycopy(src, (b % 64) * block * 2, buf, 0, block * 2)
            chain.process(buf, block)
        }
        var worst = 0L
        var total = 0L
        for (b in 0 until blocks) {
            System.arraycopy(src, (b % 64) * block * 2, buf, 0, block * 2)
            val t0 = System.nanoTime()
            chain.process(buf, block)
            val dt = System.nanoTime() - t0
            total += dt
            if (dt > worst) worst = dt
        }
        val audioNs = blocks.toLong() * block * 1_000_000_000L / FS
        val rtf = audioNs.toDouble() / total
        return Row(name, rtf, 100.0 / rtf, total / 1000.0 / blocks, worst / 1000.0)
    }

    private val eqBands = EqParameters.defaultBands().map { EqBand(it.frequencyHz, 4f, 1.5f) }
    private val eq = EqParameters(enabled = true, bands = eqBands)
    private val comp = DynamicsParameters(compressor = CompressorParameters(enabled = true, thresholdDb = -30f, ratio = 4f))
    private val loud = DynamicsParameters(loudness = LoudnessParameters(enabled = true))
    private val bass = BassParameters(true, 6f, 0.8f, 0.8f, 120f)
    private val spatial = SpatialParameters(true, SpatialMode.CONCERT_HALL, 0.8f, 1.4f)
    private val imaging = ImagingParameters(true, 1f, 2f, 0.1f, 150f)

    private fun timeNs(run: () -> Unit): Long {
        run(); run() // warm-up
        val t0 = System.nanoTime()
        run()
        return System.nanoTime() - t0
    }

    @Test
    fun writeReport() {
        val rows = listOf(
            scenario("Limiter only (all modules off)", EngineParameters()),
            scenario("Equalizer (10 bands)", EngineParameters(eq = eq)),
            scenario("Compressor", EngineParameters(dynamics = comp)),
            scenario("Bass (shelf + harmonics + punch)", EngineParameters(bass = bass)),
            scenario("Spatial (Concert Hall)", EngineParameters(spatial = spatial)),
            scenario("Stereo imaging", EngineParameters(imaging = imaging)),
            scenario("Loudness normalizer", EngineParameters(dynamics = loud)),
            scenario(
                "Everything on",
                EngineParameters(
                    masterGainDb = 2f, eq = eq, spatial = spatial, bass = bass, imaging = imaging,
                    dynamics = DynamicsParameters(
                        compressor = comp.compressor,
                        loudness = loud.loudness,
                    ),
                ),
            ),
        )
        val everything = rows.last()

        val sb = StringBuilder("# Senza Studio - P6 measurements (generated by P6MeasurementReportTest)\n\n")
        sb.append("JVM: ${System.getProperty("java.vm.name")} ${System.getProperty("java.version")}, ")
        sb.append("${Runtime.getRuntime().availableProcessors()} CPUs, ${System.getProperty("os.name")} ${System.getProperty("os.arch")}.\n")
        sb.append("48 kHz stereo, 1024-frame blocks, 20 s per scenario after a 4 s warm-up. These numbers describe the machine that ran the test, not a phone; compare rows with each other.\n\n")
        sb.append("## DSP cost per scenario (single thread)\n\n")
        sb.append("| scenario | x real time | CPU of one core | us / 1024-frame block (21333 us available) | worst block us |\n|---|---|---|---|---|\n")
        for (r in rows) {
            sb.append("| ${r.name} | ${f(r.realtimeFactor, 1)} | ${f(r.loadPercent)} % | ${f(r.microsPerBlock, 1)} | ${f(r.worstBlockMicros, 0)} |\n")
        }

        // Before / after of the optimised loops (the same work, P5 algorithm vs P6 algorithm).
        val data = program(FS * 20)
        val tmp = FloatArray(block * 2)
        fun pass(step: (FloatArray, Int) -> Unit) {
            var f = 0
            val total = data.size / 2
            while (f < total) {
                val n = minOf(block, total - f)
                System.arraycopy(data, f * 2, tmp, 0, n * 2)
                step(tmp, n)
                f += n
            }
        }
        val limOld = ReferenceLimiter(FS)
        val limNew = Limiter(FS)
        val compOld = ReferenceCompressor(FS).also { it.configure(-24.0, 4.0, 5.0, 150.0, 6.0, 0.0) }
        val compNew = Compressor(FS).also { it.configure(-24.0, 4.0, 5.0, 150.0, 6.0, 0.0) }
        val tOldLim = timeNs { pass { b, n -> limOld.process(b, n) } }
        val tNewLim = timeNs { pass { b, n -> limNew.process(b, n) } }
        val tOldComp = timeNs { pass { b, n -> compOld.process(b, n) } }
        val tNewComp = timeNs { pass { b, n -> compNew.process(b, n) } }
        sb.append("\n## Optimised loops: P5 algorithm vs P6 algorithm (20 s of program material)\n\n")
        sb.append("| stage | P5 ms | P6 ms | speed-up |\n|---|---|---|---|\n")
        sb.append("| Limiter (look-ahead 2 ms) | ${f(tOldLim / 1e6, 1)} | ${f(tNewLim / 1e6, 1)} | ${f(tOldLim.toDouble() / tNewLim, 1)}x |\n")
        sb.append("| Compressor | ${f(tOldComp / 1e6, 1)} | ${f(tNewComp / 1e6, 1)} | ${f(tOldComp.toDouble() / tNewComp, 1)}x |\n")
        sb.append("\nThe true-peak meter skips its 72 multiply-adds per sample whenever the sample window cannot raise the held maximum (bit-identical result); its saving depends on the material and is not listed here.\n")

        val dir = File("build/reports")
        dir.mkdirs()
        File(dir, "p6-measurements.md").writeText(sb.toString())
        assertTrue("full chain only ${f(everything.realtimeFactor)}x real time", everything.realtimeFactor >= 5.0)
    }

    private fun program(frames: Int): FloatArray {
        val out = stereoNoise(1f, frames, 11, 12)
        val segment = FS / 4
        for (i in 0 until frames) {
            val level = when ((i / segment) % 5) {
                0 -> 0.9f
                1 -> 0.2f
                2 -> 0.02f
                3 -> 0f
                else -> 1.6f
            }
            out[i * 2] *= level
            out[i * 2 + 1] *= level
        }
        return out
    }
}
