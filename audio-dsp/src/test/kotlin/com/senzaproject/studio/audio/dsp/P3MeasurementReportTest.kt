package com.senzaproject.studio.audio.dsp

import com.senzaproject.studio.audio.engine.BassParameters
import com.senzaproject.studio.audio.engine.ImagingParameters
import com.senzaproject.studio.audio.engine.LoudnessParameters
import com.senzaproject.studio.audio.engine.SpatialMode
import com.senzaproject.studio.audio.engine.SpatialParameters
import java.io.File
import java.util.Locale
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Measures the Phase 3 modules with the real DSP code and writes the result to
 * build/reports/p3-measurements.md (uploaded by CI). Numbers in docs/DSP_P3.md come from the same
 * procedures; this file is the authoritative, reproducible version.
 */
class P3MeasurementReportTest {
    private fun f(v: Double) = String.format(Locale.US, "%.2f", v)

    private fun bass(p: BassParameters, x: FloatArray): FloatArray {
        val b = BassEnhancer(FS).also { it.configure(BassConfig.from(p, FS)) }
        return runBlocks(x) { buf, n -> b.process(buf, n) }
    }

    private fun imager(p: ImagingParameters, x: FloatArray): FloatArray {
        val m = StereoImager(FS).also { it.configure(ImagingConfig.from(p, FS)) }
        return runBlocks(x) { buf, n -> m.process(buf, n) }
    }

    private fun spatial(p: SpatialParameters, x: FloatArray): FloatArray {
        val m = SpatialProcessor(FS).also { it.configure(SpatialConfig.from(p, FS)) }
        return runBlocks(x) { buf, n -> m.process(buf, n) }
    }

    private fun lufs(x: FloatArray): Double =
        LoudnessMeter(FS).also { m -> runBlocks(x) { b, n -> m.process(b, n) } }.integratedLufs

    @Test
    fun writeReport() {
        val sb = StringBuilder("# Senza Studio - P3 measurements (generated by P3MeasurementReportTest)\n\n")

        sb.append("## Bass harmonics (50 Hz tone, 0.25 amplitude); levels relative to the fundamental\n\n")
        sb.append("| harmonics | fundamental change dB | H2 dBr | H3 dBr | H4 dBr |\n|---|---|---|---|---|\n")
        for (h in listOf(0.25f, 0.5f, 0.75f, 1f)) {
            val out = bass(BassParameters(enabled = true, harmonics = h), sine(50.0, 0.25, 3.0))
            val a1 = toneAmplitude(out, 0, 50.0, FS, FS)
            fun r(freq: Double) = f(dbfs(toneAmplitude(out, 0, freq, FS, FS) / a1))
            sb.append("| $h | ${f(dbfs(a1 / 0.25))} | ${r(100.0)} | ${r(150.0)} | ${r(200.0)} |\n")
        }

        sb.append("\n## Bass sub shelf (60 Hz low shelf), gain in dB at tone frequency\n\n| setting | 30 Hz | 60 Hz | 120 Hz | 250 Hz | 1 kHz |\n|---|---|---|---|---|---|\n")
        for (g in listOf(-12f, 6f, 12f)) {
            val cells = listOf(30.0, 60.0, 120.0, 250.0, 1_000.0).joinToString(" | ") { fr ->
                val out = bass(BassParameters(enabled = true, subBassDb = g), sine(fr, 0.1, 2.0))
                f(dbfs(toneAmplitude(out, 0, fr, FS, FS) / 0.1))
            }
            sb.append("| $g dB | $cells |\n")
        }

        sb.append("\n## Bass punch (kick, 60 Hz burst, 0.5 amplitude): attack peak change\n\n| punch | dB |\n|---|---|\n")
        val hits = kick()
        val basePeak = peak(bass(BassParameters(enabled = true), hits).copyOfRange(0, FS)).toDouble()
        for (p in listOf(0.5f, 1f)) {
            val pk = peak(bass(BassParameters(enabled = true, punch = p), hits).copyOfRange(0, FS)).toDouble()
            sb.append("| $p | ${f(dbfs(pk / basePeak))} |\n")
        }

        sb.append("\n## Imaging: side-only tone level with mono-below 120 Hz\n\n| Hz | dB |\n|---|---|\n")
        for (fr in listOf(30.0, 60.0, 100.0, 200.0, 500.0, 2_000.0)) {
            val out = imager(ImagingParameters(enabled = true, monoBelowHz = 120f), stereoSine(fr, 0.3, -0.3, 2.0))
            sb.append("| ${fr.toInt()} | ${f(dbfs(toneAmplitude(out, 0, fr, FS, FS) / 0.3))} |\n")
        }

        sb.append("\n## Spatial scenes (intensity 1, width 1)\n\n| scene | mono in: side/in | stereo noise: level change dB | side change dB |\n|---|---|---|---|\n")
        val mono = monoNoise(0.3f, FS * 3)
        val st = stereoNoise(0.3f, FS * 3)
        for (mode in SpatialMode.entries) {
            val p = SpatialParameters(true, mode, 1f, 1f)
            val side = rmsSide(spatial(p, mono)) / rmsChannel(mono, 0)
            val o = spatial(p, st)
            sb.append("| ${mode.displayName} | ${f(side)} | ${f(dbfs(rmsAll(o) / rmsAll(st)))} | ${f(dbfs(rmsSide(o) / rmsSide(st)))} |\n")
        }

        sb.append("\n## Crossfeed (Studio, intensity 1): side-only tone level\n\n| Hz | dB |\n|---|---|\n")
        for (fr in listOf(100.0, 300.0, 700.0, 1_500.0, 5_000.0)) {
            val o = spatial(SpatialParameters(true, SpatialMode.STUDIO, 1f, 1f), stereoSine(fr, 0.3, -0.3, 2.0))
            sb.append("| ${fr.toInt()} | ${f(dbfs(toneAmplitude(o, 0, fr, FS, FS) / 0.3))} |\n")
        }

        sb.append("\n## Loudness meter\n\n| signal | reading LUFS |\n|---|---|\n")
        val a23 = Math.pow(10.0, -23.0 / 20.0)
        sb.append("| 1 kHz stereo -23 dBFS (EBU reference) | ${f(lufs(stereoSine(1_000.0, a23, a23, 5.0)))} |\n")
        for (fr in listOf(100.0, 1_000.0, 10_000.0)) {
            val a = Math.pow(10.0, -20.0 / 20.0)
            sb.append("| ${fr.toInt()} Hz stereo -20 dBFS | ${f(lufs(stereoSine(fr, a, a, 5.0)))} |\n")
        }

        sb.append("\n## True peak estimate (sine, amplitude 1.0, worst of 13 phases): error in dB\n\n| Hz | worst abs error |\n|---|---|\n")
        for (fr in listOf(1_000.0, 12_000.0, 15_000.0, 18_000.0, 20_000.0)) {
            var worst = 0.0
            for (k in 0..12) {
                val ph = Math.PI * k / 12
                val buf = FloatArray(9_600 * 2)
                for (i in 0 until 9_600) {
                    val fade = if (i < 960) 0.5 - 0.5 * Math.cos(Math.PI * i / 960) else 1.0
                    val v = (fade * Math.sin(2 * Math.PI * fr * i / FS + ph)).toFloat()
                    buf[i * 2] = v; buf[i * 2 + 1] = v
                }
                val m = LoudnessMeter(FS)
                m.process(buf, 9_600)
                worst = maxOf(worst, Math.abs(m.truePeakDb))
            }
            sb.append("| ${fr.toInt()} | ${f(worst)} |\n")
        }

        sb.append("\n## Normalizer convergence (target -20 LUFS, response 1 s)\n\n| input | output LUFS (last 5 s) | gain dB |\n|---|---|---|\n")
        for (amp in listOf(0.04f, 0.3f)) {
            val n = LoudnessNormalizer(FS).also {
                it.configure(LoudnessConfig.from(LoudnessParameters(true, -20f, 12f, 24f, 1f), FS))
            }
            val x = stereoNoise(amp, FS * 20)
            val y = runBlocks(x) { b, c -> n.process(b, c) }
            sb.append("| noise ${f(lufs(x))} LUFS | ${f(lufs(y.copyOfRange(y.size - FS * 10, y.size)))} | ${f(n.currentGainDb)} |\n")
        }

        val file = File("build/reports/p3-measurements.md")
        file.parentFile.mkdirs()
        file.writeText(sb.toString())
        assertTrue(file.length() > 500)
    }
}
